def _get_system_prompt(model: ExpertModel, rag_context: str = "") -> str:
    """Build the specialist system prompt, optionally injecting RAG context."""
    base = _DOC_EXPERT_SYSTEM if model == ExpertModel.MISTRAL_7B else _CODE_EXPERT_SYSTEM
    if rag_context:
        return base + "\n\n" + rag_context
    return base


# ─────────────────────────────────────────────────────────────────────────────
# OpenRouter call (shared by both specialist models)
# ─────────────────────────────────────────────────────────────────────────────

async def _call_openrouter(
    model_id: str,
    system_prompt: str,
    diff_text: str,
    timeout: float = 90.0,
) -> Dict[str, Any]:
    """
    Make a single OpenRouter chat completion call and parse the JSON response.
    Raises AppError on HTTP failure or JSON parse failure.
    """
    settings = get_settings()
    api_key = settings.OPENROUTER_API_KEY  # type: ignore[attr-defined]

    async with httpx.AsyncClient(timeout=timeout) as client:
        response = await client.post(
            OPENROUTER_BASE,
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
                "HTTP-Referer": settings.BACKEND_URL,
                "X-Title": "PandaHub AI Code Review",
            },
            json={
                "model": model_id,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": f"Git diff:\n\n{diff_text}"},
                ],
                "max_tokens": 4096,
                "temperature": 0.2,
            },
        )
        response.raise_for_status()

    data = response.json()
    raw = data.get("choices", [{}])[0].get("message", {}).get("content", "{}").strip()

    # Strip accidental markdown fences
    raw = re.sub(r"^```(?:json)?\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)

    try:
        return json.loads(raw.strip())
    except json.JSONDecodeError as exc:
        logger.error("OpenRouter JSON parse error. Model=%s raw=%r", model_id, raw[:300])
        raise AppError(f"Expert model '{model_id}' returned malformed JSON.") from exc


