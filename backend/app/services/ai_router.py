class DiffCategory(str, Enum):
    FUNCTIONAL    = "functional"      # logic / algorithm / bug fix
    REFACTORING   = "refactoring"     # restructure, rename, extract
    DOCUMENTATION = "documentation"   # comments, docstrings, README
    DISCUSSION    = "discussion"      # config, deps, CI/CD
    FALSE_POSITIVE = "false_positive" # whitespace, formatting, generated


# ─────────────────────────────────────────────────────────────────────────────
# Expert model definitions
# ─────────────────────────────────────────────────────────────────────────────

class ExpertModel(str, Enum):
    # OpenRouter-hosted open-weight specialists
    QWEN_CODER   = "qwen/qwen-2.5-coder-32b-instruct"   # code reasoning / AST
    MISTRAL_7B   = "mistralai/mistral-7b-instruct"        # NL / documentation
    # Anthropic fallback (existing integration)
    CLAUDE       = "claude"  # resolved via settings.AI_MODEL at call time


OPENROUTER_BASE = "https://openrouter.ai/api/v1/chat/completions"

# Routing table: category → (model, k_samples)
ROUTING_TABLE: Dict[DiffCategory, Tuple[ExpertModel, int]] = {
    DiffCategory.FUNCTIONAL:    (ExpertModel.QWEN_CODER, 3),
    DiffCategory.REFACTORING:   (ExpertModel.QWEN_CODER, 3),
    DiffCategory.DOCUMENTATION: (ExpertModel.MISTRAL_7B, 3),
    DiffCategory.DISCUSSION:    (ExpertModel.MISTRAL_7B, 3),
    DiffCategory.FALSE_POSITIVE: (ExpertModel.QWEN_CODER, 1),  # minimal pass
}


# ─────────────────────────────────────────────────────────────────────────────
# Classification heuristics (zero-cost, no model call)
# ─────────────────────────────────────────────────────────────────────────────

# File-extension signals
_DOC_EXTENSIONS   = {".md", ".rst", ".txt", ".adoc"}
_CONFIG_EXTENSIONS = {".yaml", ".yml", ".toml", ".json", ".ini", ".cfg",
                       ".env", ".lock", ".xml"}
_GENERATED_PATTERNS = (
    r"auto.?generated",
    r"do not edit",
    r"generated by",
    r"\.min\.js$",
    r"\.pb\.go$",
)

# Diff-content keyword signals
_REFACTOR_KEYWORDS = re.compile(
    r"\b(rename|refactor|extract|inline|move|reorganiz|cleanup|clean.up)\b",
    re.IGNORECASE,
)
_LOGIC_KEYWORDS = re.compile(
    r"\b(def |function |class |if |else |elif |for |while |switch |case |"
    r"async |await |return |raise |throw |try |except |catch |lambda |"
    r"algorithm|optimize|fix|bug|implement|logic)\b",
)
_DOC_KEYWORDS = re.compile(
    r'("""|\'\'\''
    r"|#\s+\w"
    r"|docstring"
    r"|readme"
    r"|changelog"
    r"|@param|@return|:param|:returns)",
    re.IGNORECASE,
)
_WHITESPACE_ONLY = re.compile(r"^[+-]\s*$", re.MULTILINE)


def _extract_changed_files(diff_text: str) -> List[str]:
    """Parse '+++ b/path' lines from a unified diff."""
    return [
        line[6:].strip()
        for line in diff_text.splitlines()
        if line.startswith("+++ b/")
    ]


def _count_changed_lines(diff_text: str) -> Tuple[int, int]:
    """Return (added, removed) line counts."""
    added = sum(1 for line in diff_text.splitlines() if line.startswith("+") and not line.startswith("+++"))
    removed = sum(1 for line in diff_text.splitlines() if line.startswith("-") and not line.startswith("---"))
    return added, removed


def classify_diff(diff_text: str) -> DiffCategory:
    """
    Classify a unified diff into a DiffCategory using heuristics.

    The classifier runs in microseconds — no model API call is made.
    It uses a weighted scoring system across four signal dimensions:
      1. File extensions
      2. Diff content keywords
      3. Changed-line ratio
      4. Generated-file patterns

    Returns the category with the highest combined signal weight.
    """
    if not diff_text.strip():
        return DiffCategory.FALSE_POSITIVE

    files = _extract_changed_files(diff_text)
    added, removed = _count_changed_lines(diff_text)

    # ── Early exit: detect auto-generated / whitespace-only diffs ──
    all_files_generated = files and all(
        any(re.search(p, f, re.IGNORECASE) for p in _GENERATED_PATTERNS)
        for f in files
    )
    if all_files_generated:
        return DiffCategory.FALSE_POSITIVE

    # Whitespace-only diff (formatting commits)
    content_lines = [
        line for line in diff_text.splitlines()
        if (line.startswith("+") and not line.startswith("+++"))
        or (line.startswith("-") and not line.startswith("---"))
    ]
    if content_lines and all(not line[1:].strip() for line in content_lines):
        return DiffCategory.FALSE_POSITIVE

    # ── Score each category ──
    scores: Dict[DiffCategory, float] = {cat: 0.0 for cat in DiffCategory}

    # File-extension & config-filename signals (weight 2.0 per matching file)
    config_filenames = {
        "Dockerfile", "Makefile", ".gitignore", "requirements.txt",
        "package.json", "package-lock.json", "Pipfile", "pyproject.toml",
    }
    config_files = sum(
        1 for f in files
        if any(f.endswith(ext) for ext in _CONFIG_EXTENSIONS)
        or f in config_filenames
        or f.endswith("requirements.txt")
    )
    doc_files = sum(
        1 for f in files
        if any(f.endswith(ext) for ext in _DOC_EXTENSIONS)
        and not f.endswith("requirements.txt")
        and f not in config_filenames
    )
    scores[DiffCategory.DOCUMENTATION] += doc_files * 2.0
    scores[DiffCategory.DISCUSSION]    += config_files * 2.0

    # Keyword signals (weight 1.0 per match, capped at 5.0)
    logic_hits   = min(len(_LOGIC_KEYWORDS.findall(diff_text)), 5)
    refactor_hits = min(len(_REFACTOR_KEYWORDS.findall(diff_text)), 5)
    doc_hits      = min(len(_DOC_KEYWORDS.findall(diff_text)), 5)

    scores[DiffCategory.FUNCTIONAL]    += logic_hits * 1.0
    scores[DiffCategory.REFACTORING]   += refactor_hits * 1.5  # stronger signal
    scores[DiffCategory.DOCUMENTATION] += doc_hits * 1.0

    # Refactoring penalty: large renames show lots of additions AND removals
    if added > 0 and removed > 0:
        ratio = min(added, removed) / max(added, removed)
        if ratio > 0.6:  # near-symmetric additions/deletions → likely rename/refactor
            scores[DiffCategory.REFACTORING] += 1.5

    # Pure addition (new feature) → functional
    if removed == 0 and added > 5:
        scores[DiffCategory.FUNCTIONAL] += 1.0

    # ── Resolve winner (exclude FALSE_POSITIVE from regular scoring) ──
    candidate_cats = [
        DiffCategory.FUNCTIONAL,
        DiffCategory.REFACTORING,
        DiffCategory.DOCUMENTATION,
        DiffCategory.DISCUSSION,
    ]
    winner = max(candidate_cats, key=lambda c: scores[c])

    # If all scores are zero (no signals at all), fall back to FUNCTIONAL
    # so we still get a code review rather than a false positive skip
    if scores[winner] == 0.0:
        return DiffCategory.FUNCTIONAL

    logger.debug(
        "Diff classification scores: %s → %s",
        {c.value: round(s, 2) for c, s in scores.items()},
        winner.value,
    )
    return winner


