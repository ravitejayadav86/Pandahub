"""
Dynamic Hybrid Expert Routing — Module 11 AI Intelligence Layer.

Architecture Overview
─────────────────────
Instead of sending every PR diff to a single monolithic model, this module:

1. **Classifies** the diff into one of five semantic categories using a
   lightweight heuristic + keyword pass (zero API cost).
2. **Dispatches** the classified task to the specialist model best suited
   for that category:
       - Code Reasoning / Logic  →  Qwen2.5-Coder-32B  (via OpenRouter, k=3)
       - Documentation / NL      →  Mistral-Instruct-7B (via OpenRouter, k=3)
       - Fallback / General      →  Claude (Anthropic, existing integration)
3. **Merges** results from k=3 parallel expert calls (majority-vote on
   severity, union of unique suggestions) into a single structured review.

Performance characteristics (from research literature):
   Hybrid routed approach: +13.2% net gain over zero-shot baseline
   Hybrid vs single best standalone model: +7.7% gain

Semantic Categories
───────────────────
  FUNCTIONAL      — logic changes, new algorithms, bug fixes
  REFACTORING     — code reorganization, rename, extract, inline
  DOCUMENTATION   — docstrings, comments, README, type hints
  DISCUSSION      — config, dependency bumps, CI/CD files
  FALSE_POSITIVE  — whitespace, formatting, auto-generated files

Routing Table
─────────────
  FUNCTIONAL   → Qwen2.5-Coder-32B  (k=3)  — AST + logic correctness
  REFACTORING  → Qwen2.5-Coder-32B  (k=3)  — structural reasoning
  DOCUMENTATION → Mistral-7B-Instruct (k=3) — natural language fluency
  DISCUSSION   → Mistral-7B-Instruct (k=3)  — config / prose reasoning
  FALSE_POSITIVE → early-exit, no model call
  FALLBACK     → Claude (Anthropic)  (k=1)  — when OpenRouter unavailable

All external calls are async (httpx). The k=3 parallel calls are launched
concurrently with asyncio.gather for minimum wall-clock latency.
"""
